-- =============================================================================
-- extraer-esquema.sql — extractor del DDL de producción de NitroAccesos
--
-- QUÉ ES: consulta de SOLO LECTURA contra los catálogos de PostgreSQL que
-- regenera el volcado completo del esquema `public` (tablas, restricciones,
-- índices, funciones, RLS, event trigger y mapa de permisos de funciones)
-- con las columnas que consume `scripts/volcado-a-migracion.py`:
--   ord       — número de bloque que fija el orden de emisión
--               (0 esquema, 1 extensión, 2 grants de esquema, 10 tablas,
--               20 restricciones, 30 índices, 40 funciones, 50 RLS,
--               60 event trigger, 80 permisos de funciones, 87 cierre).
--   objeto    — nombre corto del objeto (tabla, constraint, función, ...).
--   ddl       — sentencia SQL completa del objeto.
--   identidad — columnas IDENTITY de la tabla del bloque (solo se rellena en
--               las filas de tablas, ord 10; cadena vacía en el resto). Una
--               entrada por columna con el formato `tabla.columna=a` cuando
--               es GENERATED ALWAYS AS IDENTITY o `tabla.columna=d` cuando es
--               GENERATED BY DEFAULT AS IDENTITY; varias entradas se separan
--               con `;`. Viene de `pg_attribute.attidentity`: una columna
--               `GENERATED ... AS IDENTITY` NO tiene `column_default`, el
--               valor automático vive en `attidentity`, así que su columna en
--               `ddl` sale sin `default` y el generador la reconstruye a
--               partir de este campo.
--
-- DÓNDE: se ejecuta SOLO en el SQL Editor del proyecto de PRODUCCIÓN
-- (nitrotalentos). NUNCA en staging.
--
-- SEGURIDAD: la consulta es SOLO LECTURA — no crea, modifica ni borra nada;
-- únicamente lee catálogos del sistema (pg_class, pg_attribute, pg_constraint,
-- pg_index, pg_proc, pg_event_trigger, pg_extension).
--
-- RESULTADO: descargar el resultado como CSV (botón Export/Download del SQL
-- Editor) y guardarlo en `docs/sql/volcado-produccion-<fecha>.csv`. Ese CSV es
-- la entrada del generador `scripts/volcado-a-migracion.py`.
--
-- HISTORIAL: la consulta que produjo `volcado-produccion-2026-11-09.csv` NO
-- capturaba `attidentity`: `login_intentos.id` salía como `bigint not null` a
-- secas y la migración generada rompía el login en staging ("null value in
-- column id violates not-null constraint"). Esta versión añade la columna
-- `identidad`; el usuario verificó en producción (information_schema.columns)
-- que `login_intentos.id` con identity_generation ALWAYS es la única columna
-- identity de todo el esquema.
-- =============================================================================

with identidad as (
  select c.relname as tabla,
         a.attname as columna,
         a.attidentity
    from pg_catalog.pg_attribute a
    join pg_catalog.pg_class c on c.oid = a.attrelid
    join pg_catalog.pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public'
     and c.relkind = 'r'
     and a.attnum > 0
     and not a.attisdropped
     and a.attidentity in ('a', 'd')
)
select *
  from (
    -- 0: esquema -------------------------------------------------------------
    select '0'::text as ord,
           'schema'::text as objeto,
           'create schema if not exists extensions;'::text as ddl,
           ''::text as identidad

    union all

    -- 1: extensiones ---------------------------------------------------------
    select '1'::text,
           'extension'::text,
           format('create extension if not exists %s with schema extensions;', e.extname),
           ''::text
      from pg_catalog.pg_extension e
      join pg_catalog.pg_namespace en on en.oid = e.extnamespace
     where en.nspname = 'extensions'

    union all

    -- 2: grants de esquema ---------------------------------------------------
    select '2'::text,
           'grants-schema'::text,
           'grant usage on schema public to anon, authenticated;'::text,
           ''::text

    union all

    -- 10: tablas (con deteccion de columnas IDENTITY) ------------------------
    select '10'::text,
           c.relname,
           'create table if not exists public.' || c.relname || ' ('
             || string_agg(
                  a.attname || ' ' || format_type(a.atttypid, a.atttypmod)
                  -- una columna identity no lleva `default` (no lo tiene) ni
                  -- `not null` explicito: el generador emite GENERATED ... AS IDENTITY
                  -- a partir de la columna `identidad`.
                  || case
                       when a.attidentity = 'a' then ' GENERATED ALWAYS AS IDENTITY'
                       when a.attidentity = 'd' then ' GENERATED BY DEFAULT AS IDENTITY'
                       when a.attnotnull then ' not null'
                       else ''
                     end
                  || case
                       when a.attidentity in ('a', 'd') then ''
                       when d.adbin is null then ''
                       else ' default ' || pg_get_expr(d.adbin, d.adrelid)
                     end,
                  ', '
                  order by a.attnum)
             || ');',
           coalesce(
             string_agg(i.tabla || '.' || i.columna || '=' || i.attidentity, ';' order by i.columna),
             ''
           )
      from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
      join pg_catalog.pg_attribute a
        on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
      left join pg_catalog.pg_attrdef d
        on d.adrelid = a.attrelid and d.adnum = a.attnum
      left join identidad i
        on i.tabla = c.relname and i.columna = a.attname
     where n.nspname = 'public'
       and c.relkind = 'r'
     group by c.relname

    union all

    -- 20: restricciones ------------------------------------------------------
    select '20'::text,
           conrel.relname,
           'alter table ' || conrel.relname
             || ' add constraint ' || con.conname
             || ' ' || pg_get_constraintdef(con.oid) || ';',
           ''::text
      from pg_catalog.pg_constraint con
      join pg_catalog.pg_class conrel on conrel.oid = con.conrelid
      join pg_catalog.pg_namespace n on n.oid = conrel.relnamespace
     where n.nspname = 'public'
       and conrel.relkind = 'r'

    union all

    -- 30: indices que no son de constraint (PK/UNIQUE ya vienen en ord 20) ---
    select '30'::text,
           idx.relname,
           pg_get_indexdef(ix.indexrelid) || ';',
           ''::text
      from pg_catalog.pg_index ix
      join pg_catalog.pg_class idx on idx.oid = ix.indexrelid
      join pg_catalog.pg_class tbl on tbl.oid = ix.indrelid
      join pg_catalog.pg_namespace n on n.oid = tbl.relnamespace
     where n.nspname = 'public'
       and tbl.relkind = 'r'
       and not ix.indisprimary
       and not exists (
             select 1 from pg_catalog.pg_constraint cs
              where cs.conindid = ix.indexrelid)

    union all

    -- 40: funciones ----------------------------------------------------------
    select '40'::text,
           p.proname,
           pg_get_functiondef(p.oid),
           ''::text
      from pg_catalog.pg_proc p
      join pg_catalog.pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and p.prokind = 'f'

    union all

    -- 50: RLS habilitado -----------------------------------------------------
    select '50'::text,
           c.relname,
           format('alter table public.%s enable row level security;', c.relname),
           ''::text
      from pg_catalog.pg_class c
      join pg_catalog.pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and c.relkind = 'r'
       and c.relrowsecurity

    union all

    -- 60: event trigger de la aplicacion (los de Supabase/PostgREST los
    -- excluye el generador; aqui solo sale el nuestro) ----------------------
    select '60'::text,
           et.evtname,
           format('create event trigger %I on %s execute function %s;',
                  et.evtname, et.evtevent, etf.proname),
           ''::text
      from pg_catalog.pg_event_trigger et
      join pg_catalog.pg_proc etf on etf.oid = et.evtfoid
     where et.evtname = 'ensure_rls'

    union all

    -- 80: permisos de funciones, segun el mapa REAL de produccion ------------
    -- `has_function_privilege('anon', ...)` decide si la funcion es publica
    -- (grant a anon) o interna (revoke de anon); el generador reescribe cada
    -- fila como `revoke execute ... from public` + grant a anon si toca.
    select '80'::text,
           p.proname,
           case
             when has_function_privilege('anon', p.oid, 'EXECUTE')
               then 'grant execute on function public.' || p.proname
                    || '(' || pg_get_function_identity_arguments(p.oid) || ') to anon;'
             else 'revoke execute on function public.' || p.proname
                  || '(' || pg_get_function_identity_arguments(p.oid) || ') from anon;'
           end,
           ''::text
      from pg_catalog.pg_proc p
      join pg_catalog.pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and p.prokind = 'f'

    union all

    -- 90: cierre de permisos de tablas ---------------------------------------
    select '90'::text,
           'grants-tablas'::text,
           'revoke all on all tables in schema public from anon, authenticated;'::text,
           ''::text
  ) bloques
 order by ord::int, objeto;
